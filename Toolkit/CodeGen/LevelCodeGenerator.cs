using System;
using System.Collections;
using System.Collections.Generic;
using System.Globalization;
using System.Linq;
using System.Reflection;
using System.Text;
using LevelXML;

namespace LevelXMLUtils;

/// <summary>
/// The reverse of building a Level out of Entity objects: takes a Level (usually one imported
/// from levelXML) and writes the C# that constructs it.
/// </summary>
/// <remarks>
/// It works purely off the public LevelXML API. For every entity it constructs a default instance
/// of the same type and only emits the properties that differ from it, so the generated code stays
/// small and keeps working as LevelXML gains new entity types or properties.
///
/// Every top level entity gets a local variable named after its type and its index in the level
/// (e.g. <c>circle3</c>, <c>vehicle12</c>, <c>activateTrigger40</c>), so it is easy to map back to
/// the original XML. Entities inside a group are written inline as constructor arguments.
/// Trigger targets are wired up in a separate block at the end, because triggers can target
/// triggers that come later in the level.
///
/// Give entities readable names with <see cref="Names"/> before calling <see cref="GenerateMethod"/>.
/// The generated code needs only <c>using LevelXML;</c>.
/// </remarks>
public class LevelCodeGenerator
{
	/// <summary>
	/// Variable names to use instead of the generated ones. Keyed by reference, so use the entities
	/// of the exact Level that you pass to <see cref="GenerateMethod"/>.
	/// </summary>
	public Dictionary<Entity, string> Names { get; } = new(ReferenceEqualityComparer.Instance);

	/// <summary>How many entity names to put on each line of the final <c>new Level(...)</c>.</summary>
	public int EntitiesPerLine { get; set; } = 6;

	private const string Indent = "\t";
	private const BindingFlags Instance = BindingFlags.Public | BindingFlags.Instance;
	private const BindingFlags Hidden = BindingFlags.NonPublic | BindingFlags.Instance;

	private readonly Dictionary<Entity, string> variables = new(ReferenceEqualityComparer.Instance);
	private readonly Dictionary<Type, PropertyInfo[]> propertyCache = new();

	/// <summary>Convenience wrapper: levelXML string in, C# method out.</summary>
	public static string FromXml(string xml, string methodName = "BuildLevel")
		=> new LevelCodeGenerator().GenerateMethod(new Level(xml), methodName);

	/// <summary>
	/// Writes a complete, compilable source file: a static class with one method that rebuilds <paramref name="level"/>.
	/// </summary>
	public string GenerateClass(Level level, string className, string methodName = "Build", string @namespace = "Levels")
	{
		string method = GenerateMethod(level, methodName);
		string indented = string.Join("\n", method.TrimEnd().Split('\n').Select(line => line.Length == 0 ? line : Indent + line));
		return $"using LevelXML;\n\nnamespace {@namespace};\n\n"
			+ $"// Generated by {nameof(LevelCodeGenerator)} from levelXML.\n"
			+ $"public static class {className}\n{{\n{indented}\n}}\n";
	}

	/// <summary>
	/// Writes a <c>public static Level {methodName}()</c> method that rebuilds <paramref name="level"/>.
	/// </summary>
	public string GenerateMethod(Level level, string methodName = "BuildLevel")
	{
		// Rendering the level once fills in state that LevelXML only computes lazily, such as joints' entity indices
		level.ToXML();
		variables.Clear();
		AssignVariables(level);

		StringBuilder sb = new();
		StringBuilder body = new();
		Section(body, "Shapes", level.Shapes);
		Section(body, "Specials", level.Specials);
		Section(body, "Groups", level.Groups);
		Section(body, "Joints", level.Joints);
		Section(body, "Triggers", level.Triggers);
		sb.AppendLine($"public static Level {methodName}()");
		sb.AppendLine("{");
		sb.Append(body);
		List<string> wiring = level.Triggers.SelectMany(WireTargets).ToList();
		if (wiring.Count > 0)
		{
			sb.AppendLine($"{Indent}// Trigger targets, in firing order");
			foreach (string line in wiring)
			{
				sb.AppendLine($"{Indent}{line}");
			}
			sb.AppendLine();
		}

		sb.Append(Indent).Append("return new Level(");
		string[] all = level.Entities.Select(e => variables[e]).ToArray();
		for (int i = 0; i < all.Length; i++)
		{
			if (i % EntitiesPerLine == 0) { sb.AppendLine().Append(Indent).Append(Indent); }
			sb.Append(all[i]);
			if (i < all.Length - 1) { sb.Append(i % EntitiesPerLine == EntitiesPerLine - 1 ? "," : ", "); }
		}
		sb.AppendLine($"){Initializer(level, CreateDefault(level))};");
		sb.AppendLine("}");
		return sb.ToString();
	}

	/// <summary>A named, logical piece of a level, for <see cref="GenerateClass(Level, string, IReadOnlyList{LevelPart}, string)"/>.</summary>
	/// <param name="Name">A C# identifier in PascalCase; the part's code goes in <c>Build{Name}</c>.</param>
	/// <param name="Description">Written as a comment above the part.</param>
	/// <param name="Entities">Top level entities of the level. Every entity must be in exactly one part.</param>
	public record LevelPart(string Name, string Description, IReadOnlyCollection<Entity> Entities);

	/// <summary>
	/// Like <see cref="GenerateClass(Level, string, string, string)"/>, but splits the level into logical parts.
	/// </summary>
	/// <remarks>
	/// The class has a public field for every top level entity, grouped by part, and a <c>Build{Part}</c> method
	/// per part that creates that part's entities. Parts are built in the order given, so a part can only refer
	/// to entities (as joint ends) of itself or of earlier parts. Trigger targets are wired afterwards in
	/// <c>Wire{Part}</c> methods, where any part may refer to any other. The final <see cref="Level"/> lists
	/// entities in their original order, because draw order and trigger order are part of a level's behavior.
	/// </remarks>
	public string GenerateClass(Level level, string className, IReadOnlyList<LevelPart> parts, string @namespace = "Levels")
	{
		level.ToXML();
		variables.Clear();
		AssignVariables(level, pascalCase: true);

		Dictionary<Entity, int> partOf = new(ReferenceEqualityComparer.Instance);
		for (int i = 0; i < parts.Count; i++)
		{
			foreach (Entity entity in parts[i].Entities)
			{
				if (!variables.ContainsKey(entity))
				{
					throw new InvalidOperationException($"Part {parts[i].Name} has an entity that isn't a top level entity of the level.");
				}
				if (!partOf.TryAdd(entity, i))
				{
					throw new InvalidOperationException($"{variables[entity]} is in both {parts[partOf[entity]].Name} and {parts[i].Name}.");
				}
			}
		}
		string[] unassigned = level.Entities.Where(e => !partOf.ContainsKey(e)).Select(e => variables[e]).ToArray();
		if (unassigned.Length > 0)
		{
			throw new InvalidOperationException($"{unassigned.Length} entities aren't in any part: {string.Join(", ", unassigned.Take(10))}");
		}
		foreach (Joint joint in level.Joints)
		{
			foreach (Entity end in new[] { joint.First, joint.Second }.OfType<Entity>())
			{
				if (partOf[end] > partOf[joint])
				{
					throw new InvalidOperationException(
						$"{variables[joint]} (part {parts[partOf[joint]].Name}) is jointed to {variables[end]}, which is in the later part {parts[partOf[end]].Name}. Put that part first.");
				}
			}
		}

		StringBuilder members = new();
		StringBuilder builders = new();
		StringBuilder wirers = new();
		List<string> constructorCalls = new();
		List<string> wireCalls = new();
		foreach (LevelPart part in parts)
		{
			Entity[] entities = level.Entities.Where(e => part.Entities.Contains(e)).ToArray();
			members.AppendLine($"{Indent}// ---- {part.Name}: {part.Description}");
			foreach (Entity entity in entities)
			{
				members.AppendLine($"{Indent}public {TypeName(entity.GetType())} {variables[entity]} = null!;");
			}
			members.AppendLine();

			builders.AppendLine($"{Indent}/// <summary>{part.Description}</summary>");
			builders.AppendLine($"{Indent}private void Build{part.Name}()");
			builders.AppendLine($"{Indent}{{");
			foreach (Entity entity in entities)
			{
				builders.AppendLine($"{Indent}{Indent}{variables[entity]} = {Construct(entity, Indent + Indent, targetTyped: true)};");
			}
			builders.AppendLine($"{Indent}}}");
			builders.AppendLine();
			constructorCalls.Add($"Build{part.Name}();");

			List<string> wiring = entities.OfType<Trigger>().SelectMany(WireTargets).ToList();
			if (wiring.Count > 0)
			{
				wirers.AppendLine($"{Indent}private void Wire{part.Name}()");
				wirers.AppendLine($"{Indent}{{");
				foreach (string line in wiring) { wirers.AppendLine($"{Indent}{Indent}{line}"); }
				wirers.AppendLine($"{Indent}}}");
				wirers.AppendLine();
				wireCalls.Add($"Wire{part.Name}();");
			}
		}

		StringBuilder sb = new();
		sb.AppendLine("using LevelXML;");
		sb.AppendLine();
		sb.AppendLine($"namespace {@namespace};");
		sb.AppendLine();
		sb.AppendLine($"// Generated by {nameof(LevelCodeGenerator)} from levelXML, then split into parts.");
		sb.AppendLine($"public class {className}");
		sb.AppendLine("{");
		sb.AppendLine($"{Indent}public Level Level {{ get; }}");
		sb.AppendLine();
		sb.AppendLine($"{Indent}public static Level Build() => new {className}().Level;");
		sb.AppendLine();
		sb.Append(members);
		sb.AppendLine($"{Indent}public {className}()");
		sb.AppendLine($"{Indent}{{");
		foreach (string call in constructorCalls.Concat(wireCalls)) { sb.AppendLine($"{Indent}{Indent}{call}"); }
		sb.AppendLine();
		sb.Append($"{Indent}{Indent}Level = new Level(");
		string[] all = level.Entities.Select(e => variables[e]).ToArray();
		for (int i = 0; i < all.Length; i++)
		{
			if (i % EntitiesPerLine == 0) { sb.AppendLine().Append(Indent).Append(Indent).Append(Indent); }
			sb.Append(all[i]);
			if (i < all.Length - 1) { sb.Append(i % EntitiesPerLine == EntitiesPerLine - 1 ? "," : ", "); }
		}
		sb.AppendLine($"){Initializer(level, CreateDefault(level))};");
		sb.AppendLine($"{Indent}}}");
		sb.AppendLine();
		sb.Append(builders);
		sb.Append(wirers);
		return sb.ToString().TrimEnd() + "\n}\n";
	}

	private void Section(StringBuilder sb, string title, IEnumerable<Entity> entities)
	{
		if (!entities.Any()) { return; }
		sb.AppendLine($"{Indent}// {title}");
		foreach (Entity entity in entities)
		{
			sb.AppendLine($"{Indent}{TypeName(entity.GetType())} {variables[entity]} = {Construct(entity, Indent, targetTyped: true)};");
		}
		sb.AppendLine();
	}

	// ---------------------------------------------------------------- naming

	private void AssignVariables(Level level, bool pascalCase = false)
	{
		Assign(level.Shapes);
		Assign(level.Specials);
		Assign(level.Groups);
		Assign(level.Joints);
		Assign(level.Triggers);

		void Assign<T>(IList<T> entities) where T : Entity
		{
			for (int i = 0; i < entities.Count; i++)
			{
				string name = Names.TryGetValue(entities[i], out string? custom)
					? custom
					: entities[i].GetType().Name + i;
				// Fields are PascalCase, locals are camelCase
				variables[entities[i]] = (pascalCase ? char.ToUpperInvariant(name[0]) : char.ToLowerInvariant(name[0])) + name[1..];
			}
		}
		string[] duplicates = variables.Values.GroupBy(v => v).Where(g => g.Count() > 1).Select(g => g.Key).ToArray();
		if (duplicates.Length > 0)
		{
			throw new InvalidOperationException($"Two entities were given the same name: {string.Join(", ", duplicates)}");
		}
	}

	private string VariableFor(Entity entity, string usedBy)
		=> variables.TryGetValue(entity, out string? name)
			? name
			: throw new InvalidOperationException(
				$"{usedBy} points to a {entity.GetType().Name} that isn't a top level entity of the level, so it has no name.");

	// ---------------------------------------------------------------- entities

	/// <summary>A <c>new X(...) { ... }</c> expression for an entity, without any trigger targets.</summary>
	private string Construct(Entity entity, string indent, bool targetTyped = false)
	{
		string type = TypeName(entity.GetType());
		object defaults = CreateDefault(entity);
		string arguments = entity switch
		{
			CustomShape shape => CustomShapeArguments(shape),
			Group group => string.Join(",", group.Items.Select(child => $"\n{indent}{Indent}{Construct(child, indent + Indent)}")),
			_ => "",
		};
		string prefix = targetTyped ? "new" : $"new {type}";
		string parenthesised = arguments.Length == 0 && !targetTyped ? "" : $"({arguments})";
		return $"{prefix}{parenthesised}{Initializer(entity, defaults)}";
	}

	private string CustomShapeArguments(CustomShape shape)
	{
		return string.Join(", ", VerticesOf(shape).Select(FormatVertex));
	}

	/// <summary>The <c> { A = 1, B = 2 }</c> part, listing only the properties that differ from a fresh instance.</summary>
	private string Initializer(object instance, object defaults)
	{
		List<string> assignments = new();
		if (instance is Joint joint)
		{
			if (joint.First is not null) { assignments.Add($"First = {VariableFor(joint.First, "A joint")}"); }
			if (joint.Second is not null) { assignments.Add($"Second = {VariableFor(joint.Second, "A joint")}"); }
		}
		foreach (PropertyInfo property in SettableProperties(instance.GetType()))
		{
			string actual = FormatValue(property.GetValue(instance), property.PropertyType, property.Name);
			string original = FormatValue(property.GetValue(defaults), property.PropertyType, property.Name);
			if (actual != original)
			{
				assignments.Add($"{property.Name} = {actual}");
			}
		}
		if (assignments.Count == 0) { return ""; }
		return $" {{ {string.Join(", ", assignments)} }}";
	}


	private PropertyInfo[] SettableProperties(Type type)
	{
		if (propertyCache.TryGetValue(type, out PropertyInfo[]? cached)) { return cached; }
		PropertyInfo[] result = type.GetProperties(Instance)
			.Where(p => p.GetIndexParameters().Length == 0
				&& p.GetGetMethod() is not null
				&& p.GetSetMethod() is not null
				// Entity references (Joint.First, Target.Targeted) need variable names, so they're written explicitly
				&& !typeof(Entity).IsAssignableFrom(p.PropertyType))
			.GroupBy(p => p.Name)
			.Select(g => g.OrderByDescending(p => Depth(p.DeclaringType!)).First())
			// Base class properties first, then in source order: X, Y, Width, ...
			.OrderBy(p => Depth(p.DeclaringType!))
			.ThenBy(p => p.MetadataToken)
			.ToArray();
		propertyCache[type] = result;
		return result;
	}

	private static int Depth(Type type)
	{
		int depth = 0;
		for (Type? t = type.BaseType; t is not null; t = t.BaseType) { depth++; }
		return depth;
	}

	// ---------------------------------------------------------------- default instances

	/// <summary>
	/// What you'd get from <c>new T()</c>. Anything with all-optional/params constructors works,
	/// which covers every LevelXML type that can be made without other entities.
	/// </summary>
	private static object CreateDefault(object like)
	{
		Type type = like.GetType();
		// Custom shapes derive their default width and height from their vertices
		if (like is CustomShape shape)
		{
			return Activator.CreateInstance(type, new object[] { VerticesOf(shape).ToArray() })!;
		}
		foreach (ConstructorInfo constructor in type.GetConstructors(Instance).OrderBy(c => c.GetParameters().Length))
		{
			ParameterInfo[] parameters = constructor.GetParameters();
			if (!parameters.All(p => p.IsOptional || p.GetCustomAttribute<ParamArrayAttribute>() is not null)) { continue; }
			object?[] arguments = parameters
				.Select(p => p.GetCustomAttribute<ParamArrayAttribute>() is not null
					? Array.CreateInstance(p.ParameterType.GetElementType()!, 0)
					: p.DefaultValue)
				.ToArray();
			return constructor.Invoke(arguments);
		}
		throw new NotSupportedException($"Don't know how to make a default {type.Name}; it needs a constructor that can be called with no arguments.");
	}

	// ---------------------------------------------------------------- shapes with vertices

	/// <summary>
	/// The vertices of a polygon or art shape. Shapes imported with an empty vertex tag borrow the
	/// vertices of an earlier shape, which LevelXML only exposes internally.
	/// </summary>
	private static IList<Vertex> VerticesOf(CustomShape shape)
	{
		if (shape.Vertices.Count > 0) { return shape.Vertices; }
		FieldInfo? copied = typeof(CustomShape).GetField("CopiedShape", Hidden);
		if (copied?.GetValue(shape) is CustomShape original && !ReferenceEquals(original, shape))
		{
			return original.Vertices;
		}
		return shape.Vertices;
	}

	private static string FormatVertex(Vertex vertex)
	{
		string position = $"new Point({FormatDouble(vertex.Position.X)}, {FormatDouble(vertex.Position.Y)})";
		string handleOne = vertex.HandleOne is Point one ? $"new Point({FormatDouble(one.X)}, {FormatDouble(one.Y)})" : "null";
		string handleTwo = vertex.HandleTwo is Point two ? $"new Point({FormatDouble(two.X)}, {FormatDouble(two.Y)})" : "null";
		if (vertex.HandleTwo is not null) { return $"new Vertex({position}, {handleOne}, {handleTwo})"; }
		if (vertex.HandleOne is not null) { return $"new Vertex({position}, {handleOne})"; }
		return $"new Vertex({position})";
	}

	// ---------------------------------------------------------------- triggers

	private IEnumerable<string> WireTargets(Trigger trigger)
	{
		string triggerName = variables[trigger];
		foreach (Target target in trigger.Targets)
		{
			Type targetType = target.GetType();
			Type entityType = targetType.GetGenericArguments()[0];
			string targeted = VariableFor(target.Targeted, $"Trigger {triggerName}");
			IEnumerable<string> actions = target.Actions.Select(action => Construct(action));
			yield return $"{triggerName}.AddTarget(new {TypeName(targetType)}({string.Join(", ", new[] { targeted }.Concat(actions))}));";
		}
	}

	/// <summary>Actions have no children or references, so they're just a type and some properties.</summary>
	private string Construct(ITriggerAction action)
	{
		object defaults = CreateDefault(action);
		return $"new {TypeName(action.GetType())}(){Initializer(action, defaults)}";
	}

	// ---------------------------------------------------------------- literals

	private static string FormatValue(object? value, Type declaredType, string propertyName)
	{
		if (value is null) { return "null"; }
		Type type = Nullable.GetUnderlyingType(declaredType) ?? declaredType;
		if (value is string s) { return FormatString(s); }
		if (value is bool b) { return b ? "true" : "false"; }
		if (value is double d) { return FormatDouble(d); }
		if (value is float f) { return FormatDouble(f) + "f"; }
		if (value is int or long or uint or short or byte) { return Convert.ToString(value, CultureInfo.InvariantCulture)!; }
		if (type.IsEnum) { return FormatEnum(type, value); }
		if (value is LevelXMLTag.HWBool hwBool)
		{
			return hwBool.ToString() switch { "t" => "true", "f" => "false", _ => "LevelXMLTag.HWBool.NaN" };
		}
		if (type.IsValueType && type.Namespace == nameof(LevelXML))
		{
			// The Happy Wheels "enums": structs with named static readonly values that wrap a double
			string text = value.ToString()!;
			FieldInfo? named = type.GetFields(BindingFlags.Public | BindingFlags.Static)
				.Where(field => field.FieldType == type)
				.FirstOrDefault(field => field.GetValue(null)!.ToString() == text);
			if (named is not null) { return $"{TypeName(type)}.{named.Name}"; }
			if (double.TryParse(text, NumberStyles.Float, CultureInfo.CurrentCulture, out double number))
			{
				return $"({TypeName(type)}){FormatDouble(number)}";
			}
		}
		throw new NotSupportedException($"Can't write {type.Name} value of property {propertyName} as code.");
	}

	private static string FormatEnum(Type type, object value)
		=> Enum.IsDefined(type, value)
			? $"{TypeName(type)}.{Enum.GetName(type, value)}"
			: $"({TypeName(type)}){Convert.ToInt64(value, CultureInfo.InvariantCulture)}";

	private static string FormatDouble(double value)
	{
		if (double.IsNaN(value)) { return "double.NaN"; }
		if (double.IsPositiveInfinity(value)) { return "double.PositiveInfinity"; }
		if (double.IsNegativeInfinity(value)) { return "double.NegativeInfinity"; }
		return value.ToString("R", CultureInfo.InvariantCulture);
	}

	private static string FormatString(string value)
	{
		StringBuilder sb = new("\"");
		foreach (char c in value)
		{
			sb.Append(c switch
			{
				'"' => "\\\"",
				'\\' => "\\\\",
				'\n' => "\\n",
				'\r' => "\\r",
				'\t' => "\\t",
				< ' ' or > '~' => $"\\u{(int)c:x4}",
				_ => c.ToString(),
			});
		}
		return sb.Append('"').ToString();
	}

	private static string TypeName(Type type)
	{
		if (type.IsGenericType)
		{
			string name = type.Name[..type.Name.IndexOf('`')];
			return $"{name}<{string.Join(", ", type.GetGenericArguments().Select(TypeName))}>";
		}
		return type.DeclaringType is null ? type.Name : $"{TypeName(type.DeclaringType)}.{type.Name}";
	}
}
